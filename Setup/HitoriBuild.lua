-- 사용자 C++ 모듈 (UE의 게임 모듈). SourceDir의 .h/.cpp를 정적 라이브러리로 만든다.
-- 엔진 헤더를 그대로 include하고 엔진 클래스를 상속할 수 있다. 에디터 헤더는 쓸 수 없다(게임 exe에도 들어가므로).
-- 헤더 툴이 SourceDir의 UCLASS로 <GeneratedDir>/<Name>/*.generated.h를 만든다.
-- exe에서 /WHOLEARCHIVE로 링크해야 UCLASS 정적 등록 객체가 버려지지 않는다 (EditorApp/GameApp의 Modules).
-- 라이브러리 파일은 <Name>Module.lib이다. 게임 exe(<Name>.exe)와 이름이 겹치지 않게 한다.
function Hitori.ModuleLibName(Name)
	return Name .. "Module"
end

function Hitori.ModuleProject(Ctx, Name, SourceDir)
	SourceDir = path.getabsolute(SourceDir)

	-- 엔진과 같은 PCH(EnginePCH.h)를 강제 include로 쓴다. 사용자 .cpp가 PCH include를 적지 않아도 된다.
	local PchSource = Ctx.ProjectFilesDir .. "/" .. Name .. "PCH.cpp"
	os.mkdir(Ctx.ProjectFilesDir)
	os.writefile_ifnotequal("// Generated by Setup/HitoriBuild.lua. PCH for module " .. Name .. ".\n#include \"EnginePCH.h\"\n", PchSource)

	project (Name)
		location (Ctx.ProjectFilesDir)
		kind     "StaticLib"
		targetname (Hitori.ModuleLibName(Name))
		Hitori.CommonSettings(Ctx)

		pchheader "EnginePCH.h"
		pchsource (PchSource)
		forceincludes { "EnginePCH.h" }

		files
		{
			SourceDir .. "/**.h",
			SourceDir .. "/**.hpp",
			SourceDir .. "/**.cpp",
			PchSource,
		}
		vpaths
		{
			["Source/*"] = SourceDir .. "/**",
			["Generated"] = PchSource,
		}

		Hitori.RuntimeIncludeDirs(Ctx)
		includedirs
		{
			SourceDir,
			Ctx.GeneratedDir .. "/" .. Name,
			IncludeDir.PhysX,
			IncludeDir.PxShared,
		}

		dependson { "HitoriHeaderTool", "HitoriEngine" }
		prebuildcommands { Hitori.HeaderToolCommand(Ctx, Name, { SourceDir }) }
end


-- UClass는 헤더의 정적 객체가 등록하므로, exe가 직접 참조하지 않는 클래스의 .obj를 링커가 버리면
-- 그 클래스가 등록되지 않아 씬 로드 때 액터가 사라진다. 라이브러리 .obj를 전부 링크해 막는다.
function Hitori.WholeArchive(LibNames)
	for _, Name in ipairs(LibNames) do
		linkoptions { "/WHOLEARCHIVE:" .. Name }
	end
end

-- 에디터 실행 파일. Opts:
--   Location : .vcxproj 폴더 (기본값: 엔진 솔루션이면 Source/Editor, 아니면 ProjectFilesDir)
--   Modules  : 함께 링크할 사용자 모듈(Hitori.ModuleProject) 이름 목록. /WHOLEARCHIVE로 링크한다.
--   TargetName: exe 파일 이름 (기본값: 프로젝트 이름)
--   Files    : 추가로 컴파일할 파일
--   DebugArgs: 디버깅할 때 넘길 커맨드라인 인자 목록
function Hitori.EditorApp(Ctx, Name, Opts)
	Opts = Opts or {}
	local Modules = Opts.Modules or {}

	project (Name)
		location (Opts.Location or Location(Ctx, "Source/Editor"))
		kind     "WindowedApp"
		Hitori.CommonSettings(Ctx)

		files
		{
			E("Source/Editor/EditorEntryPoint.cpp"),
			E("Source/Editor/EngineProject.rc"),   -- 창·exe 아이콘
			-- 프로세스 ANSI 코드 페이지를 UTF-8로 둔다. 한글 프로젝트 경로가 char 경로 API에서 깨지지 않게 한다.
			E("Source/Runtime/Launch/HitoriApp.manifest"),
		}
		files (Opts.Files or {})
		if Opts.DebugArgs then debugargs (Opts.DebugArgs) end
		if Opts.TargetName then targetname (Opts.TargetName) end

		-- .rc의 아이콘 경로("..\\..\\Resources\\...")가 .rc 폴더 기준이 되게 한다
		resincludedirs { E("Source/Editor"), E("Source/Runtime") }

		Hitori.EditorCompileSettings(Ctx)

		links (Modules)
		links { "HitoriEditorCore", "HitoriEngine", "ImGui", "Lua" }
		for _, Module in ipairs(Modules) do Hitori.WholeArchive({ Hitori.ModuleLibName(Module) }) end
		Hitori.WholeArchive({ "HitoriEditorCore", "HitoriEngine" })

		Hitori.LinkPhysX()
		Hitori.LinkNvCloth()
		Hitori.LinkSystemLibs()

		local ExtraCommands = {}
		if Ctx.IsEngineSolution then
			local PublishSymbols = 'call "' .. E("PublishSymbols.bat") .. '" "$(Configuration)" "Post-build" --no-pause'
			ExtraCommands["DebugPublishSymbols"] = { PublishSymbols }
			ExtraCommands["ReleasePublishSymbols"] = { PublishSymbols }
		end
		Hitori.LinkFbxSdk(ExtraCommands)

		filter "configurations:ObjViewer"
			targetname "ObjViewer"

		filter "configurations:Benchmark"
			targetname "Benchmark"

		filter "configurations:Benchmark_Debug"
			targetname "Benchmark_Debug"

		filter {}
end

-- 패키징용 게임 실행 파일. 에디터 소스와 ImGui를 링크하지 않는다.
-- 에셋과 셰이더는 실행 중에 읽으므로 배포 시 콘텐츠를 함께 복사한다. Opts는 EditorApp과 같다.
function Hitori.GameApp(Ctx, Name, Opts)
	Opts = Opts or {}
	local Modules = Opts.Modules or {}

	project (Name)
		location (Opts.Location or Location(Ctx, "Source/Game"))
		kind     "WindowedApp"
		Hitori.CommonSettings(Ctx)

		pchheader "EnginePCH.h"
		pchsource (E("Source/Game/GamePCH.cpp"))

		files
		{
			E("Source/Game/**.h"),
			E("Source/Game/**.cpp"),
			E("Source/Game/**.rc"),   -- 아이콘을 넣을 때
			E("Source/Runtime/Launch/HitoriApp.manifest"),   -- 에디터와 같은 이유 (UTF-8 코드 페이지)
		}
		files (Opts.Files or {})
		if Opts.DebugArgs then debugargs (Opts.DebugArgs) end
		if Opts.TargetName then targetname (Opts.TargetName) end

		Hitori.RuntimeIncludeDirs(Ctx)

		links (Modules)
		links { "HitoriEngine", "Lua" }
		-- 에디터와 같은 이유. 게임 코드는 라이트 액터 등을 직접 참조하지 않아 특히 빠지기 쉽다.
		for _, Module in ipairs(Modules) do Hitori.WholeArchive({ Hitori.ModuleLibName(Module) }) end
		Hitori.WholeArchive({ "HitoriEngine" })

		Hitori.LinkPhysX()
		Hitori.LinkNvCloth()
		Hitori.LinkSystemLibs()
end

-- 셰이더를 VS에서 편집하기 위한 보기 전용 프로젝트 (언리얼의 Shaders와 같은 역할).
-- 새 셰이더 파일은 솔루션을 다시 생성해야 목록에 반영된다.
function Hitori.ShadersProject(Ctx)
	project "Shaders"
		location (Ctx.ProjectFilesDir or path.join(Ctx.Root, "Intermediate/ProjectFiles"))
		kind     "Utility"

		files { E("Resources/Shader/**.hlsl"), E("Resources/Shader/**.hlsli") }
		vpaths { ["*"] = E("Resources/Shader/**") }

		filter "files:**.hlsl"
			excludefrombuild "On"

		filter "files:**.hlsli"
			excludefrombuild "On"

		filter {}
end
