-- 런타임. 에디터를 모른다. include 경로에 Source/Editor가 없는 것이 그 방벽이다.
function Hitori.EngineProject(Ctx)
	project "HitoriEngine"
		location (Location(Ctx, "Source/Runtime"))
		kind     "StaticLib"
		Hitori.CommonSettings(Ctx)

		pchheader "EnginePCH.h"
		pchsource (E("Source/Runtime/EnginePCH.cpp"))

		files
		{
			E("Source/Runtime/**.h"),
			E("Source/Runtime/**.hpp"),
			E("Source/Runtime/**.cpp"),
			IncludeDir.DDSLoader .. "/*.h",
			IncludeDir.DDSLoader .. "/*.cpp",
		}

		includedirs
		{
			E("Source/Runtime"),
			Ctx.GeneratedDir .. "/Runtime",
			IncludeDir.stb,
			IncludeDir.json,
			IncludeDir.DDSLoader,
			IncludeDir.miniaudio,
			IncludeDir.lua,
			IncludeDir.sol2,
			IncludeDir.PhysX,
			IncludeDir.PxShared,
			IncludeDir.NvCloth,
		}
		BuildConfigIncludeDirs(Ctx)

		links { "Lua" }

		dependson { "HitoriHeaderTool" }
		prebuildcommands { Hitori.HeaderToolCommand(Ctx, "Runtime", { E("Source/Runtime") }) }

		-- files: 필터는 드라이브 문자(C:)가 든 절대 경로를 못 받고, 상대 패턴은 현재 디렉터리 기준으로 푼다.
		-- 다른 폴더의 스크립트에서 불려도 엔진 파일을 가리키도록 잠시 엔진 폴더로 옮겨 정의한다.
		local PrevDir = os.getcwd()
		os.chdir(EngineDir)

		-- sol2 템플릿이 섹션 수 제한을 넘긴다
		filter "files:Source/Runtime/Script/**.cpp"
			buildoptions { "/bigobj" }

		filter "files:Source/ThirdParty/DDSLoader/**.cpp"
			enablepch "Off"

		filter "files:Source/Runtime/Audio/MiniaudioImpl.cpp"
			enablepch "Off"

		filter {}
		os.chdir(PrevDir)
		-- 시스템 라이브러리는 여기서 링크하지 않는다 (Hitori.LinkSystemLibs 설명 참고).
end

-- 에디터 코드 전체 (진입점 제외). 엔진 폴더의 HitoriEditor.exe와
-- 사용자 프로젝트의 <Name>Editor.exe가 같은 라이브러리를 링크한다.
-- ObjViewer/Benchmark 구성에서 쓰는 Programs 코드도 여기 들어간다.
function Hitori.EditorCoreProject(Ctx)
	project "HitoriEditorCore"
		location (Location(Ctx, "Source/Editor"))
		kind     "StaticLib"
		Hitori.CommonSettings(Ctx)

		pchheader "EnginePCH.h"
		pchsource (E("Source/Editor/EditorPCH.cpp"))

		files
		{
			E("Source/Editor/**.h"),
			E("Source/Editor/**.cpp"),
			E("Source/Programs/**.h"),
			E("Source/Programs/**.cpp"),
		}

		removefiles
		{
			E("Source/Programs/HitoriHeaderTool/**"),
			-- 진입점은 exe마다 따로 컴파일한다 (Hitori.EditorApp)
			E("Source/Editor/EditorEntryPoint.cpp"),
		}

		Hitori.EditorCompileSettings(Ctx)

		-- 엔진의 generated.h가 먼저 만들어져야 한다
		dependson { "HitoriHeaderTool", "HitoriEngine" }
		prebuildcommands
		{
			Hitori.HeaderToolCommand(Ctx, "Editor",
			{
				E("Source/Editor"),
				E("Source/Programs/ObjViewer"),
				E("Source/Programs/Benchmark"),
			})
		}
end

