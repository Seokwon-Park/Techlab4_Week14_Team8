-- Hitori 엔진 프로젝트 정의 모듈.
-- 엔진 솔루션(premake5.lua)과 사용자 C++ 프로젝트 솔루션이 같은 정의를 쓰도록 함수로 묶어 둔다.
-- 프로젝트 솔루션은 이 파일을 include한 뒤 Hitori.MakeContext로 출력 위치를 정하고
-- Hitori.DefineEngineProjects / Hitori.EditorApp / Hitori.GameApp을 호출한다.
--
-- 경로는 모두 엔진 폴더 기준 절대 경로로 만든다. premake는 상대 경로를 "지금 실행 중인 스크립트" 기준으로
-- 풀기 때문에, 다른 폴더의 premake5.lua에서 이 함수들을 불러도 엔진 소스를 가리키게 하려면 절대 경로가 필요하다.

Hitori = Hitori or {}

