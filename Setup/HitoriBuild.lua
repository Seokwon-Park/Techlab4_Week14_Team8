-- 솔루션마다 다른 출력 위치를 담는다.
--   Root            : 솔루션 루트 (절대 경로). 엔진 솔루션이면 엔진 폴더.
--   ProjectFilesDir : 엔진 쪽 .vcxproj를 둘 폴더. nil이면 엔진 소스 폴더 안에 둔다(엔진 솔루션).
--                     사용자 프로젝트 솔루션은 엔진 폴더의 .vcxproj와 겹치지 않게 자기 폴더에 둔다.
--   BuildDir        : Bin/Intermediate가 생기는 폴더 (기본값 Root/Build)
--   GeneratedDir    : 헤더 툴이 *.generated.h를 쓰는 폴더 (기본값 Root/Intermediate/Generated)
--   DebugDir        : 디버깅 작업 디렉터리 (기본값 Root)
function Hitori.MakeContext(Opts)
	Opts = Opts or {}
	local Ctx = {}
	Ctx.Root            = path.getabsolute(Opts.Root or EngineDir)
	Ctx.ProjectFilesDir = Opts.ProjectFilesDir and path.getabsolute(Opts.ProjectFilesDir) or nil
	Ctx.BuildDir        = path.getabsolute(Opts.BuildDir or path.join(Ctx.Root, "Build"))
	Ctx.GeneratedDir    = path.getabsolute(Opts.GeneratedDir or path.join(Ctx.Root, "Intermediate/Generated"))
	Ctx.DebugDir        = Opts.DebugDir or Ctx.Root
	Ctx.IsEngineSolution = (Ctx.ProjectFilesDir == nil)
	Ctx.BinDir          = Ctx.BuildDir .. "/Bin/" .. Hitori.OutputDir
	Ctx.IntDir          = Ctx.BuildDir .. "/Intermediate/" .. Hitori.OutputDir
	-- 헤더 툴 (UE의 UnrealHeaderTool 역할). 엔진·에디터·사용자 모듈이 빌드 전에 이 exe로 *.generated.h를 만든다.
	Ctx.HeaderTool      = '"' .. Ctx.BinDir .. '/HitoriHeaderTool.exe"'

	-- 프로젝트 솔루션의 exe는 엔진 폴더 밖에 생기므로 엔진 폴더와 자기 프로젝트 파일을 빌드 설정 헤더로 넘긴다.
	-- 커맨드라인 define 대신 헤더를 쓰는 것은 한글 경로가 컴파일러 명령줄의 코드 페이지에서 깨지지 않게 하려는 것이다.
	Ctx.BuildConfigDir  = nil
	if Opts.ProjectFile then
		Ctx.ProjectFile = path.getabsolute(Opts.ProjectFile)
		Ctx.BuildConfigDir = Ctx.GeneratedDir .. "/BuildConfig"
		local Header = table.concat(
		{
			"// Generated by Setup/HitoriBuild.lua. Regenerate project files instead of editing.",
			"#pragma once",
			'#define HITORI_ENGINE_DIR u8"' .. EngineDir .. '"',
			'#define HITORI_PROJECT_FILE u8"' .. Ctx.ProjectFile .. '"',
			"",
		}, "\n")
		local HeaderPath = Ctx.BuildConfigDir .. "/HitoriBuildConfig.h"
		-- 내용이 같으면 쓰지 않는다. 다시 생성할 때마다 엔진 전체가 다시 컴파일되지 않게 한다.
		os.mkdir(Ctx.BuildConfigDir)
		if os.writefile_ifnotequal(Header, HeaderPath) < 0 then error("Cannot write " .. HeaderPath) end
	end
	return Ctx
end

-- 빌드 설정 헤더(HitoriBuildConfig.h) 폴더. 엔진 솔루션에는 없다.
local function BuildConfigIncludeDirs(Ctx)
	if Ctx.BuildConfigDir then includedirs { Ctx.BuildConfigDir } end
end

-- 엔진 솔루션에서는 소스 폴더(Solution Explorer "모든 파일 표시"에서 폴더 구조가 보이게),
-- 프로젝트 솔루션에서는 ProjectFilesDir에 .vcxproj를 둔다.
local function Location(Ctx, InSource)
	return Ctx.ProjectFilesDir or E(InSource)
end

-- 헤더 툴 prebuild 명령. ModuleName은 generated 하위 폴더 이름이자 모듈 이름이다.
function Hitori.HeaderToolCommand(Ctx, ModuleName, SourceDirs)
	local Command = Ctx.HeaderTool .. ' ' .. ModuleName .. ' "' .. Ctx.GeneratedDir .. '/' .. ModuleName .. '"'
	for _, Dir in ipairs(SourceDirs) do
		Command = Command .. ' "' .. Dir .. '"'
	end
	return Command
end


