-- premake의 filter는 project()를 만나면 초기화된다.
-- 두 프로젝트가 같은 런타임(/MDd vs /MD)으로 컴파일되지 않으면 링크가 실패하므로
-- 공통 설정을 함수로 묶어 각 프로젝트에서 호출한다.
function Hitori.CommonSettings(Ctx)
	language   "C++"
	cppdialect "C++20"
	staticruntime "off"
	characterset  "Unicode"

	targetdir (Ctx.BinDir)
	objdir    (Ctx.IntDir)
	-- 에셋·쉐이더를 상대 경로로 읽으므로 작업 디렉터리는 솔루션 루트다.
	debugdir  (Ctx.DebugDir)

	defines
	{
		"WIN32_LEAN_AND_MEAN",
		"NOMINMAX",
		"UNICODE",
		"_UNICODE",
		"SOL_ALL_SAFETIES_ON=1",
	}

	filter "files:**.hlsl"
		excludefrombuild "On"

	filter "system:windows"
		systemversion "latest"
		buildoptions { "/utf-8" }
		defines { "ENGINE_PLATFORM_WINDOWS" }

	filter "configurations:Debug"
		defines { "ENGINE_DEBUG", "_DEBUG" }
		runtime  "Debug"
		symbols  "on"

	filter "configurations:Release"
		defines  { "ENGINE_RELEASE", "NDEBUG" }
		runtime  "Release"
		optimize "on"
		symbols  "on"

	-- 에디터 없이 OBJ 파일만 열어보는 Viewer 빌드
	filter "configurations:ObjViewer"
		defines  { "ENGINE_RELEASE", "NDEBUG", "OBJ_VIEWER" }
		runtime  "Release"
		optimize "on"
		symbols  "on"

	filter "configurations:Benchmark_Debug"
		defines  { "ENGINE_DEBUG", "_DEBUG", "BENCHMARK" }
		runtime  "Debug"
		symbols  "on"

	filter "configurations:Benchmark"
		defines  { "ENGINE_RELEASE", "NDEBUG", "BENCHMARK" }
		runtime  "Release"
		optimize "speed"
		-- /GL + /LTCG는 끈다. 켠 exe가 Defender ML 탐지(Trojan:Win32/Wacatac)에 오탐으로 걸렸다.
		vectorextensions "AVX2"
		-- /GS-(버퍼 보안 검사 끄기)는 성능 이득이 거의 없고 백신 휴리스틱 오탐을 부르기 쉬워 켜 둔다 (기본값 /GS)
		buildoptions { "/Gw" }
		symbols  "on"

	filter "configurations:Shipping"
		defines  { "ENGINE_RELEASE", "ENGINE_SHIPPING", "NDEBUG" }
		runtime  "Release"
		optimize "speed"
		symbols  "on"

	filter "configurations:DebugPublishSymbols"
		defines { "ENGINE_DEBUG", "_DEBUG" }
		runtime "Debug"
		symbols "on"

	filter "configurations:ReleasePublishSymbols"
		defines { "ENGINE_RELEASE", "NDEBUG" }
		runtime "Release"
		optimize "on"
		symbols "on"

	filter {}
end


-- d3d11·dxgi 등 시스템 라이브러리. exe 프로젝트만 링크한다.
-- 정적 라이브러리가 임포트 라이브러리를 품고 있으면 exe의 /WHOLEARCHIVE가 그것까지 끌어와
-- __NULL_IMPORT_DESCRIPTOR 중복 정의(LNK2005)가 난다.
function Hitori.LinkSystemLibs()
	links
	{
		"d3d11.lib",
		"dxgi.lib",
		"dxguid.lib",
		"d3dcompiler.lib",
	}
end

-- PhysX SDK 링크와 구성별 DLL 복사 (exe 프로젝트용)
function Hitori.LinkPhysX()
	includedirs { IncludeDir.PhysX, IncludeDir.PxShared }
	links
	{
		"PhysX_64.lib",
		"PhysXCommon_64.lib",
		"PhysXFoundation_64.lib",
		"PhysXCooking_64.lib",
		"PhysXExtensions_static_64.lib",
		"PhysXVehicle_static_64.lib",
		"PhysXPvdSDK_static_64.lib",
	}

	local Dlls =
	{
		"PhysX_64.dll",
		"PhysXCommon_64.dll",
		"PhysXFoundation_64.dll",
		"PhysXCooking_64.dll",
	}

	for _, Config in ipairs(Hitori.Configurations) do
		local SdkConfig = SdkConfigOf(Config)
		local Commands = {}
		for _, Dll in ipairs(Dlls) do
			local DllPath = E(path.join("Source/ThirdParty/PhysX/bin", SdkConfig, Dll))
			table.insert(Commands, '{COPYFILE} "' .. DllPath .. '" "%{cfg.targetdir}"')
		end

		filter ("configurations:" .. Config)
			libdirs { E(path.join("Source/ThirdParty/PhysX/lib", SdkConfig)) }
			postbuildcommands (Commands)
	end
	filter {}
end

-- NvCloth SDK의 구성별 링크와 DLL 복사
function Hitori.LinkNvCloth()
	includedirs { IncludeDir.NvCloth }

	local SdkRoot = E("Source/ThirdParty/NvCloth")
	for _, Config in ipairs(Hitori.Configurations) do
		local SdkConfig = SdkConfigOf(Config)
		local LibraryName = SdkConfig == "debug" and "NvClothDEBUG_x64" or "NvCloth_x64"
		local DllPath = path.join(SdkRoot, "bin", SdkConfig, LibraryName .. ".dll")

		filter ("configurations:" .. Config)
			libdirs { path.join(SdkRoot, "lib", SdkConfig) }
			links { LibraryName .. ".lib" }
			postbuildcommands { '{COPYFILE} "' .. DllPath .. '" "%{cfg.targetdir}"' }
	end
	filter {}
end

-- FBX SDK 헤더. FBX 해석은 에디터에서 하고 Runtime/Game은 SDK에 의존하지 않는다.
function Hitori.FbxSdkCompileSettings()
	includedirs { path.join(FbxSdkRoot, "include") }
	defines { "FBXSDK_SHARED" }
end

-- FBX SDK 링크와 구성별 DLL 복사 (에디터 exe용). ExtraCommands[Config]는 같은 구성에서 이어 돌 명령 목록.
function Hitori.LinkFbxSdk(ExtraCommands)
	links { "libfbxsdk.lib" }
	for _, Config in ipairs(Hitori.Configurations) do
		local SdkLibDir = path.join(FbxSdkRoot, "lib/x64", SdkConfigOf(Config))
		local Commands = { '{COPYFILE} "' .. path.join(SdkLibDir, "libfbxsdk.dll") .. '" "%{cfg.targetdir}"' }
		for _, Command in ipairs((ExtraCommands and ExtraCommands[Config]) or {}) do
			table.insert(Commands, Command)
		end

		filter ("configurations:" .. Config)
			libdirs { SdkLibDir }
			postbuildcommands (Commands)
	end
	filter {}
end


