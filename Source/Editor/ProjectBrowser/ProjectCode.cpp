	bool WriteTextFile(const fs::path& File, const FString& Text, FString& OutError)
	{
		std::ofstream Out(File, std::ios::binary);
		if (Out) Out << Text;
		if (!Out)
		{
			OutError = "Cannot write file: " + FPaths::ToUtf8(File);
			return false;
		}
		return true;
	}

	FString MakeGameModeHeader(const FString& ModuleName)
	{
		const FString ClassName = ProjectCode::SampleGameModeClass(ModuleName);
		return
			"#pragma once\n"
			"\n"
			"#include \"GameFramework/GameModeBase.h\"\n"
			"#include \"" + ModuleName + "GameMode.generated.h\"\n"
			"\n"
			"// " + ModuleName + " 프로젝트의 기본 GameMode. Config/DefaultGame.ini의 GlobalDefaultGameMode가 이 클래스를 가리킨다.\n"
			"// 씬마다 다른 GameMode를 쓰려면 World Settings의 GameMode Override로 고른다.\n"
			"// 엔진 클래스(AActor, APawn, APlayerController 등)를 상속한 클래스를 이 폴더에 더 만들 수 있다.\n"
			"// UCLASS()가 있는 헤더는 마지막 #include로 \"<헤더 이름>.generated.h\"를 넣는다.\n"
			"UCLASS()\n"
			"class " + ClassName + " : public AGameModeBase\n"
			"{\n"
			"\tGENERATED_BODY()\n"
			"public:\n"
			"\t" + ClassName + "();\n"
			"};\n";
	}

	FString MakeGameModeSource(const FString& ModuleName)
	{
		const FString ClassName = ProjectCode::SampleGameModeClass(ModuleName);
		return
			"#include \"" + ModuleName + "GameMode.h\"\n"
			"\n"
			+ ClassName + "::" + ClassName + "()\n"
			"{\n"
			"\t// 플레이할 때 만들 클래스를 이름으로 정한다. 찾을 수 없으면 엔진 기본 클래스를 쓴다.\n"
			"\tDefaultPawnClass = \"ADefaultPawn\";\n"
			"\tPlayerControllerClass = \"APlayerController\";\n"
			"}\n";
	}

	// 프로젝트 폴더의 빌드 결과물은 저장소에 넣지 않는다.
	constexpr const char* ProjectGitIgnore =
		"# Hitori C++ project: generated by the engine\n"
		"/Build/\n"
		"/Intermediate/\n"
		"/Saved/\n"
		"/.vs/\n"
		"*.slnx\n"
		"*.vcxproj\n"
		"*.vcxproj.filters\n"
		"*.vcxproj.user\n"
		"editor.ini\n"
		"imgui.ini\n";

	// 명령을 숨은 콘솔로 실행하고 출력(stdout+stderr)을 모은다. 실패하면 -1.
	int32 RunAndCapture(const std::wstring& CommandLine, const fs::path& WorkingDir, FString& OutOutput)
	{
		SECURITY_ATTRIBUTES Security = { sizeof(Security), nullptr, TRUE };
		HANDLE ReadPipe = nullptr;
		HANDLE WritePipe = nullptr;
		if (!CreatePipe(&ReadPipe, &WritePipe, &Security, 0)) return -1;
		SetHandleInformation(ReadPipe, HANDLE_FLAG_INHERIT, 0);

		STARTUPINFOW Startup = { sizeof(Startup) };
		Startup.dwFlags = STARTF_USESTDHANDLES;
		Startup.hStdOutput = WritePipe;
		Startup.hStdError = WritePipe;
		Startup.hStdInput = nullptr;

		PROCESS_INFORMATION Process = {};
		std::wstring Mutable = CommandLine;
		const BOOL bStarted = CreateProcessW(nullptr, Mutable.data(), nullptr, nullptr, TRUE, CREATE_NO_WINDOW,
			nullptr, WorkingDir.c_str(), &Startup, &Process);
		CloseHandle(WritePipe);
		if (!bStarted)
		{
			CloseHandle(ReadPipe);
			return -1;
		}

		char Buffer[4096];
		DWORD Read = 0;
		while (ReadFile(ReadPipe, Buffer, sizeof(Buffer), &Read, nullptr) && Read > 0)
			OutOutput.append(Buffer, Read);
		CloseHandle(ReadPipe);

		WaitForSingleObject(Process.hProcess, INFINITE);
		DWORD ExitCode = 1;
		GetExitCodeProcess(Process.hProcess, &ExitCode);
		CloseHandle(Process.hThread);
		CloseHandle(Process.hProcess);
		return static_cast<int32>(ExitCode);
	}
