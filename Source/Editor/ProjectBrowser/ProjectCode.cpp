FString ProjectCode::ValidateModuleName(const FString& Name)
{
	if (Name.empty()) return "Enter a name.";
	if (!std::isalpha(static_cast<unsigned char>(Name[0]))) return "C++ project name must start with a letter.";
	for (const char C : Name)
	{
		const unsigned char U = static_cast<unsigned char>(C);
		if (!(std::isalnum(U) || C == '_'))
			return "C++ project name can use only letters, digits and '_' (it becomes a C++ module and class prefix).";
	}
	return {};
}

FString ProjectCode::SampleGameModeClass(const FString& ModuleName)
{
	return "A" + ModuleName + "GameMode";
}

bool ProjectCode::WriteModuleTemplate(const fs::path& ProjectDir, const FString& ModuleName, FString& OutError)
{
	OutError = ValidateModuleName(ModuleName);
	if (!OutError.empty()) return false;

	const fs::path ModuleDir = ProjectDir / L"Source" / FPaths::FromUtf8(ModuleName);
	std::error_code Ec;
	fs::create_directories(ModuleDir, Ec);
	if (Ec)
	{
		OutError = "Cannot create folder: " + FPaths::ToUtf8(ModuleDir) + " (" + Ec.message() + ")";
		return false;
	}

	const fs::path BaseName = FPaths::FromUtf8(ModuleName + "GameMode");
	if (!WriteTextFile(ModuleDir / (BaseName.native() + L".h"), MakeGameModeHeader(ModuleName), OutError)) return false;
	if (!WriteTextFile(ModuleDir / (BaseName.native() + L".cpp"), MakeGameModeSource(ModuleName), OutError)) return false;

	const fs::path GitIgnore = ProjectDir / L".gitignore";
	if (!fs::exists(GitIgnore, Ec) && !WriteTextFile(GitIgnore, ProjectGitIgnore, OutError)) return false;
	return true;
}

fs::path ProjectCode::SolutionFile(const fs::path& ProjectFile)
{
	FProjectDescriptor Descriptor;
	FString Name;
	if (Descriptor.Load(ProjectFile)) Name = Descriptor.Name;
	if (Name.empty()) Name = FPaths::ToUtf8(ProjectFile.stem());
	return ProjectFile.parent_path() / (FPaths::FromUtf8(Name).native() + L".slnx");
}

bool ProjectCode::GenerateProjectFiles(const fs::path& ProjectFile, FString& OutLog, FString& OutError)
{
	const fs::path Script = FPaths::EngineFile(L"Setup/GenerateProjectFiles.bat");
	std::error_code Ec;
	if (!fs::exists(Script, Ec))
	{
		OutError = "Engine script not found: " + FPaths::ToUtf8(Script);
		return false;
	}

	// cmd /s /c "..." 는 바깥 따옴표 한 쌍만 벗기고 나머지를 그대로 실행한다.
	const std::wstring CommandLine = L"cmd.exe /d /s /c \"\"" + Script.wstring() + L"\" \"" +
		fs::absolute(ProjectFile, Ec).wstring() + L"\" --no-pause\"";
	OutLog.clear();
	const int32 ExitCode = RunAndCapture(CommandLine, ProjectFile.parent_path(), OutLog);
	if (ExitCode != 0)
	{
		OutError = ExitCode < 0 ? FString("Cannot run GenerateProjectFiles.bat.")
			: "Generating project files failed (exit code " + std::to_string(ExitCode) + ").";
		return false;
	}
	return true;
}
